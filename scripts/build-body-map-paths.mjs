#!/usr/bin/env node
/**
 * Converts MuscleMap's Swift path data (MIT, © Melih Colpan) into
 * src/app/(protected)/health/gym/_components/body-map-paths.ts.
 *
 *   node scripts/build-body-map-paths.mjs <path-to-MuscleMap-checkout>
 *
 * Keeps our 18 muscles plus inert silhouette parts; drops MuscleMap's
 * sub-group overlay shapes (upper-chest, inner-quad, front-deltoid, ...).
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(process.argv[2] ?? "");
if (!process.argv[2]) {
  console.error("usage: node scripts/build-body-map-paths.mjs <MuscleMap checkout>");
  process.exit(1);
}

const MUSCLES = [
  "trapezius",
  "deltoids",
  "chest",
  "upper-back",
  "serratus",
  "biceps",
  "triceps",
  "forearm",
  "abs",
  "obliques",
  "lower-back",
  "gluteal",
  "quadriceps",
  "hamstring",
  "adductors",
  "hip-flexors",
  "calves",
  "tibialis",
];
const INERT = ["head", "hair", "neck", "hands", "feet", "knees", "ankles"];

const dataDir = join(root, "Sources/MuscleMap/Data");
const kebab = (s) => s.replace(/([A-Z])/g, "-$1").toLowerCase();

const boxSrc = readFileSync(join(dataDir, "BodyPathData.swift"), "utf8");
function viewBox(name) {
  const m = new RegExp(
    `static let ${name} = BodyViewBox\\(\\s*origin: CGPoint\\(x: (\\d+), y: (\\d+)\\),\\s*size: CGSize\\(width: (\\d+), height: (\\d+)\\)`,
  ).exec(boxSrc);
  if (!m) throw new Error(`viewBox ${name} not found`);
  return m.slice(1, 5).map(Number);
}

function parts(file) {
  const src = readFileSync(join(dataDir, file), "utf8");
  const out = [];
  for (const block of src.split("BodyPartPathData(").slice(1)) {
    const slug = kebab(/slug:\s*\.(\w+)/.exec(block)[1]);
    const muscle = MUSCLES.includes(slug) ? slug : null;
    if (!muscle && !INERT.includes(slug)) continue;
    const paths = [...block.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
    out.push({ slug, muscle, paths });
  }
  return out;
}

const commit = execFileSync("git", ["-C", root, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
const data = {};
for (const sex of ["male", "female"]) {
  data[sex] = {};
  for (const side of ["front", "back"]) {
    const cap = (s) => s[0].toUpperCase() + s.slice(1);
    data[sex][side] = {
      viewBox: viewBox(sex + cap(side)),
      parts: parts(`${cap(sex)}${cap(side)}Paths.swift`),
    };
  }
}

const header = `/**
 * GENERATED by scripts/build-body-map-paths.mjs — do not edit by hand.
 * Source: https://github.com/melihcolpan/MuscleMap @ ${commit}
 * MIT License, © Melih Colpan. See THIRD_PARTY_NOTICES.md.
 *
 * \`muscle\` is set for our 18 trainable muscles, null for inert silhouette
 * parts. MuscleMap's sub-group overlay shapes are dropped.
 */
import type { Muscle } from "@/modules/health/types";

export interface BodyMapPart {
  slug: string;
  muscle: Muscle | null;
  paths: string[];
}
export interface BodyMapView {
  viewBox: [number, number, number, number];
  parts: BodyMapPart[];
}

export const BODY_MAP: Record<"male" | "female", Record<"front" | "back", BodyMapView>> = `;
const outFile = "src/app/(protected)/health/gym/_components/body-map-paths.ts";
writeFileSync(outFile, `${header}${JSON.stringify(data, null, 2)};\n`);
console.log(`wrote ${outFile}`);
